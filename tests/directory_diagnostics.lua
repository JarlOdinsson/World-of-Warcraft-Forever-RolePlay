local sender = "Spencer Raven-ClassicBetaPvE2"
local function Last(a) return a.trace.records[#a.trace.records] end
Test("guild first channel duplicate remains visible with exact raw metadata", function(f, addon, a)
    Check(a:Receive(packet, "GUILD", sender, 0, ""), true)
    Check(a:Receive(packet, "CHANNEL", sender, 9, "ForeverRPActivity"), false)
    Check(Last(a).outcome, "duplicate"); Check(Last(a).reason, "identical-advertisement")
    Check(Last(a).sender, sender); Check(Last(a).localID, "9")
