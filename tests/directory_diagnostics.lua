Test("isolation excludes inbound social records and outbound routes but preserves native state", function(f, addon, a)
    IsInGuild, IsInGroup = function() return true end, function() return true end
    f:Peer(sender)
    a:Receive(packet, "GUILD", sender)
    local native = addon.Presence.players[sender]
    local refreshes, resets = 0, 0
    addon.PlayerMarkers = {Refresh = function() refreshes = refreshes + 1 end}
    addon.LayerEvidence = {Reset = function() resets = resets + 1 end, Payload = function() return nil end}
    a.queue = {{route = {channel = "GUILD"}}}
    a:SetChannelOnly(true)
    Check(native.activity, nil); Check(addon.Presence.players[sender], native)
    Check(native.confirmed, true); Check(#a.queue, 0); Check(next(a.lastReceives), nil)
    Check(refreshes, 1); Check(resets, 1)
    Check(a:Receive(packet, "GUILD", sender), false); Check(Last(a).reason, "excluded-by-isolation")
    Check(Last(a).outcome, "ignored"); Check(native.activity, nil)
    a:Tick(); Check(#a:Routes(), 1); Check(a:Routes()[1].channel, "CHANNEL")
    Check(addon.Communication:SendActivity(packet, "PARTY"), false)
    Check(Last(a).reason, "isolation"); Check(Last(a).api, "not-called")
    Check(a:Receive(packet, "CHANNEL", sender, 7, "ForeverRPActivity"), true)
    a:SetChannelOnly(false); Check(native.activity, nil); Check(#a:Routes(), 3)
    Check(a:Receive(packet, "GUILD", sender), true)
end)
